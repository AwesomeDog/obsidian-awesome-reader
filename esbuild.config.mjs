import esbuild from "esbuild";
import {rm} from "node:fs/promises";
import {builtinModules} from "node:module";
import path from "node:path";

const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

if (prod) {
	await Promise.all(["main.js", "styles.css", "build"].map(path => rm(path, {force: true, recursive: true})));
}

const context = await esbuild.context({
	banner: {js: banner},
	entryPoints: {main: "src/main.ts", styles: "src/styles.css"},
	bundle: true,
	alias: {
		"lie": path.resolve("src/native-promise.ts"),
		"localforage": path.resolve("src/no-op-localforage.ts"),
		"jszip/dist/jszip": "jszip/lib/index.js",
		"setimmediate": path.resolve("src/set-immediate.ts"),
	},
	external: [
		"obsidian", "electron", "@codemirror/*", "@lezer/*",
		...builtinModules,
	],
	format: "cjs",
	target: "es2022",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	minify: prod,
	outdir: ".",
	entryNames: "[name]",
});

if (prod) {
	await context.rebuild();
	await context.dispose();
} else {
	await context.watch();
}
